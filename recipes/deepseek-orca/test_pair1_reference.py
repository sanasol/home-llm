"""Run: python -m unittest test_pair1_reference -v.

External fixture is COMMITTED Sushi data, not generated by this codec. It was
produced by Sashimi's numpy decode at the revision in safetensors metadata.
Override SUSHI_SRC to select a checkout of the pinned Sushi revision.
"""
import hashlib
import itertools
import json
import os
from pathlib import Path
import subprocess
import unittest

import numpy as np

import pair1_reference as ref
from stq import PERM


FIXTURE_SHA256 = "bfb3428e0657d0141d1a3c2cae254d63dfab8ae4d3c7a3ffd013c76ac7d8ddbe"


def fixture():
    root = Path(os.environ.get("SUSHI_SRC", "/tmp/sushi-src"))
    name = "src/exl3/fixtures/exl3_pair1_tiles.safetensors"
    # Read the Git object itself, not an unverified mutable working-tree file.
    raw = subprocess.check_output(["git", "-C", str(root), "show", ref.SOURCE_SHA + ":" + name])
    if hashlib.sha256(raw).hexdigest() != FIXTURE_SHA256:
        raise AssertionError("pinned external fixture content changed")
    size = int.from_bytes(raw[:8], "little")
    header = json.loads(raw[8:8 + size])
    payload = raw[8 + size:]
    arrays = {}
    for key, info in header.items():
        if key == "__metadata__":
            continue
        if info["dtype"] != "U16":
            raise AssertionError("unexpected fixture dtype")
        lo, hi = info["data_offsets"]
        arrays[key] = np.frombuffer(payload[lo:hi], dtype="<u2").reshape(info["shape"])
    return arrays, header.get("__metadata__", {})


def bitwise_windows(packed):
    """Deliberately scalar independent MSB-first circular stream oracle."""
    n = len(packed)
    stream = []
    for i in range(0, n, 2):
        word = int(packed[i]) | (int(packed[i + 1]) << 16)
        stream.extend((word >> b) & 1 for b in range(31, -1, -1))
    windows = []
    for t in range(256):
        end = (t + 1) * n // 16
        cw = 0
        for at in range(end - 16, end):
            cw = (cw << 1) | stream[at % len(stream)]
        windows.append(cw)
    return np.array(windows, dtype=np.int64)


class PairReferenceTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.external, cls.metadata = fixture()

    def test_external_sashimi_tiles_bit_exact_all_21_rates(self):
        self.assertEqual(self.metadata.get("sashimi"), "01b215e0337a71ea0f32f41567e234c4816ae1cb")
        for n in range(24, 65, 2):
            with self.subTest(n=n):
                packed = self.external[f"trellis_n{n}"]
                want = self.external[f"decoded_n{n}"]
                got = ref.decode_tiles(packed).astype(np.float16).view(np.uint16)
                np.testing.assert_array_equal(got, want)
                for tile in packed:
                    np.testing.assert_array_equal(ref.unpack_codes(tile), bitwise_windows(tile))
                # Packing an externally generated stream, not a self-generated path.
                codes = ref.unpack_codes(packed)[..., 1::2]
                np.testing.assert_array_equal(ref.pack_pair_states(codes, n), packed)

    def test_frozen_table_digest_and_known_half_bits(self):
        canonical = "".join(str(n) + "".join(f",{v:08x}" for v in row) + "\n"
                            for n, row in zip(range(24, 65, 2), ref.PAIR1_ROWS))
        self.assertEqual(hashlib.sha256(canonical.encode()).hexdigest()[:8], ref.TABLE_DIGEST)
        for n, cw, bits in ((24, 1, (0x3C74, 0xBDAA)),
                            (32, 0x1234, (0x3822, 0xB086)),
                            (38, 1, (0x3FA4, 0x3610)),
                            (40, 1, (0x3FA6, 0x3610)),
                            (48, 0x15, (0x37C6, 0xA9D0)),
                            (64, 0xFFFF, (0x3B10, 0x3C0C))):
            np.testing.assert_array_equal(ref.pair1_table(n)[cw].astype(np.float16).view(np.uint16), bits)

    def test_fractional_schedules_and_word_layout(self):
        for n, pattern in ((24, [3]), (28, [3, 4]), (32, [4]), (40, [5])):
            q = ref.pair_fresh_bits(n)
            np.testing.assert_array_equal(q, np.resize(pattern, 128))
            self.assertEqual(int(q.sum()), 16 * n)
            rng = np.random.default_rng(n)
            fresh = rng.integers(0, 1 << q, size=(2, 128))
            packed = ref.pack_fresh(fresh, n)
            codes = ref.unpack_codes(packed)[..., 1::2]
            np.testing.assert_array_equal(codes & ((1 << q) - 1), fresh)
        # First stream bit is word bit31, hence high bit of the SECOND halfword.
        fresh = np.zeros(128, dtype=np.int64)
        fresh[0] = 4
        packed = ref.pack_fresh(fresh, 24)
        self.assertEqual(packed[0], 0)
        self.assertEqual(packed[1], 0x8000)
        self.assertEqual(np.count_nonzero(packed), 1)

    def test_pair_cost_dp_matches_exhaustive_circular_paths(self):
        rng = np.random.default_rng(1701)
        table = rng.normal(size=(16, 2))
        for ks in (np.array([2, 1, 2]), np.array([1, 2, 1, 2])):
            x = rng.normal(size=(len(ks), 2))
            brute_cost = np.full(1 << (4 - ks[0]), np.inf)
            mask = len(brute_cost) - 1
            for pin in range(len(brute_cost)):
                for fresh in itertools.product(*(range(1 << k) for k in ks)):
                    cw, path = pin, []
                    for k, f in zip(ks, fresh):
                        cw = ((cw << int(k)) | f) & 15
                        path.append(cw)
                    if cw & mask == pin:
                        brute_cost[pin] = min(brute_cost[pin], float(np.sum((table[path] - x) ** 2)))
                path, cost = ref.viterbi_pairs(x, ks, table, pin)
                self.assertAlmostEqual(cost, brute_cost[pin], places=12)
                self.assertEqual(int(path[0]) >> int(ks[0]), pin)
                self.assertEqual(int(path[-1]) & mask, pin)
                self.assertAlmostEqual(cost, float(np.sum((table[path] - x) ** 2)), places=12)
            _, exact = ref.exact_tail_biting(x, ks, table)
            self.assertAlmostEqual(exact, brute_cost.min(), places=12)
            _, free = ref.viterbi_pairs(x, ks, table)
            self.assertLessEqual(free, exact + 1e-12)
        # The second observation must influence the chosen JOINT pair codeword.
        table = np.array([[0, 0], [0, 5], [1, 0], [1, 5]], dtype=float)
        a, _ = ref.viterbi_pairs([[0, 5]], [1], table)
        self.assertEqual(a[0], 1)
        ties, _ = ref.viterbi_pairs([[0, 0], [0, 0]], [1, 1], np.zeros((4, 2)))
        np.testing.assert_array_equal(ties, [0, 0])

    def test_encoder_scores_actual_decoded_pairs_and_closes_tail(self):
        rng = np.random.default_rng(28)
        for n in (24, 28, 32, 40):
            with self.subTest(n=n):
                target = rng.normal(size=(1, 256))
                packed, costs = ref.encode_tiles(target, n)
                codes = ref.unpack_codes(packed)[..., 1::2]
                np.testing.assert_array_equal(ref.pack_pair_states(codes, n), packed)
                decoded = ref.decode_tiles(packed)[..., PERM].astype(np.float64)
                self.assertAlmostEqual(costs[0], float(np.sum((target - decoded) ** 2)), places=10)
                self.assertLess(costs[0], float(np.sum(target ** 2)))
                # External Sashimi output is an exactly representable target.
                external_target = self.external[f"decoded_n{n}"][:1].view(np.float16).astype(np.float32)[:, PERM]
                encoded, errors = ref.encode_tiles(external_target, n)
                self.assertEqual(errors[0], 0.0)
                np.testing.assert_array_equal(ref.decode_tiles(encoded)[:, PERM], external_target)

    def test_validation(self):
        for n in (16, 25, 66, 28.0, True):
            with self.assertRaises(ValueError):
                ref.pair_fresh_bits(n)
        for bad in (np.zeros((1, 255)), np.full((1, 256), np.nan)):
            with self.assertRaises(ValueError):
                ref.encode_tiles(bad, 28)
        with self.assertRaises(ValueError):
            ref.unpack_codes(np.zeros(28, dtype=np.int64))
        with self.assertRaises(ValueError):
            ref.pack_fresh(np.full(128, 8), 28)
        states = ref.unpack_codes(self.external["trellis_n28"][0])[1::2]
        states[0] ^= 16
        with self.assertRaises(ValueError):
            ref.pack_pair_states(states, 28)
        with self.assertRaises(ValueError):
            ref.exact_tail_biting(np.zeros((128, 2)), ref.pair_fresh_bits(28), ref.pair1_table(28))
        empty, costs = ref.encode_tiles(np.empty((0, 256)), 28)
        self.assertEqual(empty.shape, (0, 28))
        self.assertEqual(costs.shape, (0,))


if __name__ == "__main__":
    unittest.main()
